window.currentLang = 'fa';

window.setLanguage = function(lang) {
  if (lang !== 'fa' && lang !== 'en') return;
  window.currentLang = lang;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'fa' ? 'rtl' : 'ltr';

  // Update body font class
  if (lang === 'fa') {
    document.body.classList.add('lang-fa');
    document.body.classList.remove('lang-en');
  } else {
    document.body.classList.add('lang-en');
    document.body.classList.remove('lang-fa');
  }

  // Update all data-i18n elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (window.translations[lang] && window.translations[lang][key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = window.translations[lang][key];
      } else {
        el.innerHTML = window.translations[lang][key];
      }
    }
  });

  // Update language switch button text
  const langToggleBtn = document.getElementById('langToggleBtn');
  if (langToggleBtn) {
    langToggleBtn.textContent = window.translations[lang].switchLang;
  }

  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
};

window.getTranslation = function(key) {
  return (window.translations[window.currentLang] && window.translations[window.currentLang][key]) 
    ? window.translations[window.currentLang][key] 
    : key;
};
